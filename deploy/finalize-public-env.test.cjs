const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { finalize } = require('./finalize-public-env.cjs')
test('inlines browser settings and updates references without rewriting server assignments', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'public-env-test-'))
  try {
    const dist = path.join(root, '.next')
    fs.mkdirSync(path.join(dist, 'static/chunks'), { recursive: true })
    fs.mkdirSync(path.join(dist, 'server'), { recursive: true })
    fs.writeFileSync(path.join(dist, 'static/chunks/app-0123456789abcdef.js'), 'console.log(process.env.NEXT_PUBLIC_SERVER_URL)')
    fs.writeFileSync(path.join(dist, 'server/route.js'), 'process.env.NEXT_PUBLIC_SERVER_URL ||= "http://localhost:3000"; const chunk="app-0123456789abcdef.js";')
    fs.writeFileSync(path.join(dist, 'manifest.json'), '{"file":"app-0123456789abcdef.js"}')
    const [[oldHash, newHash]] = finalize(root, { NEXT_PUBLIC_SERVER_URL: 'https://store.example' })
    const server = fs.readFileSync(path.join(dist, 'server/route.js'), 'utf8')
    assert.match(server, /process\.env\.NEXT_PUBLIC_SERVER_URL \|\|=/)
    assert.doesNotThrow(() => new Function(server))
    assert.equal(server.includes(oldHash), false)
    assert.ok(server.includes(newHash))
    const manifest = JSON.parse(fs.readFileSync(path.join(dist, 'manifest.json'), 'utf8'))
    const client = fs.readFileSync(path.join(dist, 'static/chunks', manifest.file), 'utf8')
    assert.equal(client, 'console.log("https://store.example")')
  } finally { fs.rmSync(root, { recursive: true, force: true }) }
})
